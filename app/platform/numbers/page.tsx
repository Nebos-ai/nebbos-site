function LanguageBar({ languages }: { languages: Record<string, number> }) {
  const entries = Object.entries(languages).sort(([, a], [, b]) => b - a);
  const total = entries.reduce((sum, [, n]) => sum + n, 0) || 1;
  const palette = ["var(--accent-2)", "var(--gold)", "var(--scene-2)", "var(--scene-3)", "var(--ink-3)", "var(--muted)"];
  return (
    <div>
      <div style={{ display: "flex", height: 12, borderRadius: 6, overflow: "hidden", background: "var(--paper-2)" }}>
        {entries.map(([name, n], i) => (
          <span key={name} title={`${name}: ${formatInt(n)} lines`} style={{ width: `${(n / total) * 100}%`, background: palette[i % palette.length], display: "block", height: "100%" }} />
        ))}
      </div>
      <div style={{ display: "grid", gridTemplateColumns: "repeat(auto-fit, minmax(160px, 1fr))", gap: "6px 20px", fontSize: 12, color: "var(--ink-2)", fontFamily: "var(--font-mono)", marginTop: 12 }}>
        {entries.map(([name, n], i) => (
          <div key={name}>
            <span style={{ display: "inline-block", width: 8, height: 8, borderRadius: 2, marginRight: 8, background: palette[i % palette.length], verticalAlign: "middle" }} />
            <strong style={{ color: "var(--ink)" }}>{name}</strong> · {formatInt(n)}
          </div>
        ))}
      </div>
    </div>
  );
}

