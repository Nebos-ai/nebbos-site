function TrendChart({ title, values, months, current, tone = "muted" }: {
  title: string;
  values: number[];
  months: string[];
  current: number;
  tone?: "muted" | "accent";
}) {
  const max = Math.max(...values, current) || 1;
  const min = Math.min(...values, 0);
  const range = max - min || 1;
  const W = 220;
  const H = 60;
  const pad = 4;
  const step = values.length > 1 ? (W - pad * 2) / (values.length - 1) : 0;
  const points = values.map((v, i) => {
    const x = pad + i * step;
    const y = pad + (H - pad * 2) * (1 - (v - min) / range);
    return `${x.toFixed(1)},${y.toFixed(1)}`;
  }).join(" ");
  const stroke = tone === "accent" ? "var(--accent-2)" : "var(--gold)";
  const earliest = values.find(v => v > 0) ?? 0;
  const multiplier = earliest > 0 ? (current / earliest) : 0;
  const firstMonth = months[0] ?? "";
  const lastMonth = months[months.length - 1] ?? "";

  return (
    <div style={{ borderTop: "1px solid var(--rule)", paddingTop: 16 }}>
      <p style={{
        fontFamily: "var(--font-mono)",
        fontSize: 10,
        color: "var(--ink-3)",
        letterSpacing: "0.12em",
        textTransform: "uppercase",
        fontWeight: 600,
        margin: "0 0 8px",
      }}>{title}</p>
      <p style={{
        fontFamily: "var(--font-serif)",
        fontSize: "clamp(22px, 2.4vw, 30px)",
        fontWeight: 500,
        color: "var(--ink)",
        letterSpacing: "-0.025em",
        lineHeight: 1,
        margin: "0 0 6px",
        fontVariantNumeric: "tabular-nums",
      }}>{formatCompact(current)}</p>
      {multiplier > 1.5 && (
        <p style={{ fontSize: 11, color: "var(--ink-3)", margin: "0 0 10px", fontFamily: "var(--font-mono)" }}>
          {formatCompact(earliest)} → {formatCompact(current)} · <strong style={{ color: stroke }}>{multiplier.toFixed(1)}×</strong>
        </p>
      )}
      <svg viewBox={`0 0 ${W} ${H}`} style={{ width: "100%", height: 60, display: "block", marginTop: 4 }} aria-hidden="true">
        <polyline
          points={points}
          fill="none"
          stroke={stroke}
          strokeWidth={1.5}
          strokeLinecap="round"
          strokeLinejoin="round"
        />
        {values.map((v, i) => {
          const x = pad + i * step;
          const y = pad + (H - pad * 2) * (1 - (v - min) / range);
          return <circle key={i} cx={x} cy={y} r={1.6} fill={stroke} />;
        })}
      </svg>
      <div style={{ display: "flex", justifyContent: "space-between", fontSize: 10, color: "var(--muted)", fontFamily: "var(--font-mono)", marginTop: 4, letterSpacing: "0.04em" }}>
        <span>{firstMonth}</span>
        <span>{lastMonth}</span>
      </div>
    </div>
  );
}

