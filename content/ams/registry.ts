export function assetsByCategory(cat: string): AmsAsset[] {
  return AMS_ASSETS.filter(a => a.category === cat);
}

export function assetsByStatus(s: AmsStatus): AmsAsset[] {
  return AMS_ASSETS.filter(a => a.status === s);
}

export function assetsByOwner(team: string): AmsAsset[] {
  return AMS_ASSETS.filter(a => (a.nebbosOwner ?? "").includes(team));
}

export function amsCategories(): string[] {
  return Array.from(new Set(AMS_ASSETS.map(a => a.category)));
}

export function amsCountByStatus(): Record<AmsStatus, number> {
  const counts: Record<AmsStatus, number> = {
    have: 0, "in-progress": 0, need: 0, "not-relevant": 0, "not-assessed": 0,
  };
  for (const a of AMS_ASSETS) counts[a.status]++;
  return counts;
}