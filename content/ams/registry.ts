export type AmsStatus =
  | "have"
  | "in-progress"
  | "need"
  | "not-relevant"
  | "not-assessed";

export type AmsTier = "core" | "growth" | "enterprise";

export interface AmsAsset {
  /** Category grouping (18 total). */
  category: string;
  /** Asset name from the taxonomy. */
  name: string;
  /** Audiences that consume it. */
  audience: string[];
  /** Sales-cycle stage the asset shows up in. */
  stage: string;
  /** Which functional area typically owns it (industry-standard). */
  functionalArea: string;
  /** File format(s). */
  format: string;
  /** How often it's refreshed. */
  refresh: string;
  /** Maturity tier — core = every company · growth = scaling · enterprise = major corporation. */
  tier: AmsTier;
  /** What the asset is. */
  description: string;
  /** A publicly-recognizable example, "—" if usually private. */
  publicExample: string;
  /** Nebbos state on this asset. */
  status: AmsStatus;
  /** The Nebbos team(s) that own this asset in the ratified 11-team topology. */
  nebbosOwner?: string;
  /** URL or path to the asset if have / in-progress. */
  nebbosSource?: string;
  /** Additional context — why need / not-relevant / any explanatory note. */
  nebbosNote?: string;
}

